"""
FastAPI REST Router for Synthea Synthetic Demo Patients.
Exposes endpoints for generating synthetic populations, listing demo profiles,
inspecting unified clinical timelines, and admitting synthetic patients into hospital wards.

All endpoints strictly serve synthetic data for demonstration, UI, and test purposes.
SyntheticMass (synthea.mitre.org) is retired and strictly avoided.
"""

import logging
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional
from fastapi import APIRouter, HTTPException, Query
from pydantic import BaseModel, Field

_src_dir = str(Path(__file__).resolve().parent.parent.parent / "src")
if _src_dir not in sys.path:
    sys.path.insert(0, _src_dir)

from vh.synthea.config import SyntheaGenerationConfig
from vh.synthea.service import SYNTHETIC_DISCLAIMER, demo_data_service

logger = logging.getLogger("DemoPatientsAPI")
router = APIRouter(prefix="/demo-patients", tags=["Demo Patients (Synthea)"])


class GeneratePatientsRequest(BaseModel):
    """Parameters for on-demand Synthea population generation."""
    seed: int = Field(default=42, description="Random seed for deterministic generation")
    clinician_seed: int = Field(default=101, description="Clinician assignment seed")
    reference_date: str = Field(default="2026-03-01", description="Reference simulation date (YYYY-MM-DD)")
    population: int = Field(default=2, ge=1, le=50, description="Number of synthetic patients to generate")
    state: str = Field(default="Massachusetts", description="US State for demographic distribution")
    city: Optional[str] = Field(default=None, description="Optional city within state")
    gender: Optional[str] = Field(default=None, description="Optional gender filter (M or F)")
    age_range: Optional[List[int]] = Field(default=None, description="Optional [min_age, max_age]")
    allow_docker: bool = Field(default=False, description="Attempt Docker container execution if available")


@router.get("")
async def list_demo_patients():
    """
    List all indexed synthetic demo patients.
    Returns lightweight summary cards with key clinical counts and primary diagnoses.
    """
    try:
        summaries = demo_data_service.list_patients()
        return {
            "disclaimer": SYNTHETIC_DISCLAIMER,
            "total": len(summaries),
            "patients": [s.model_dump() for s in summaries],
        }
    except Exception as e:
        logger.error(f"Error listing demo patients: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=str(e))


@router.get("/{patient_id}")
async def get_demo_patient_profile(patient_id: str):
    """
    Retrieve full structured clinical profile for a specific synthetic patient.
    Includes active conditions, medications, allergies, vitals, labs, procedures,
    immunizations, and care plans.
    """
    profile = demo_data_service.get_patient_profile(patient_id)
    if not profile:
        raise HTTPException(
            status_code=404,
            detail=f"Synthetic demo patient '{patient_id}' not found in active index"
        )
    out = profile.model_dump()
    out["disclaimer"] = SYNTHETIC_DISCLAIMER
    return out


@router.get("/{patient_id}/timeline")
async def get_demo_patient_timeline(patient_id: str):
    """
    Retrieve unified chronological clinical timeline across all 9 FHIR resource categories
    (encounters, conditions, observations, medications, allergies, procedures, immunizations, care plans).
    """
    timeline = demo_data_service.get_patient_timeline(patient_id)
    if not timeline:
        raise HTTPException(
            status_code=404,
            detail=f"Synthetic demo patient '{patient_id}' not found for timeline retrieval"
        )
    out = timeline.model_dump()
    out["disclaimer"] = SYNTHETIC_DISCLAIMER
    return out


@router.get("/{patient_id}/raw")
async def get_raw_fhir_bundle(patient_id: str):
    """
    Retrieve the exact, raw FHIR R4 JSON Transaction Bundle as generated by Synthea.
    """
    raw_bundle = demo_data_service.get_raw_bundle(patient_id)
    if not raw_bundle:
        raise HTTPException(
            status_code=404,
            detail=f"Raw FHIR bundle for patient '{patient_id}' not found"
        )
    return raw_bundle


@router.post("/generate")
async def generate_demo_patients(req: GeneratePatientsRequest):
    """
    Generate new synthetic patients with Synthea.
    Executes self-hosted Synthea generator (local Docker or deterministic engine),
    validates 100% of FHIR R4 bundles, and updates the live service index.
    """
    try:
        age_tuple = None
        if req.age_range and len(req.age_range) == 2:
            age_tuple = (req.age_range[0], req.age_range[1])

        config = SyntheaGenerationConfig(
            seed=req.seed,
            clinician_seed=req.clinician_seed,
            reference_date=req.reference_date,
            population=req.population,
            state=req.state,
            city=req.city,
            gender=req.gender,
            age_range=age_tuple,
            synthea_version="v3.3.0",
            exporter_fhir=True,
        )

        result = demo_data_service.generate_population(
            config=config,
            allow_docker=req.allow_docker,
        )
        return result
    except Exception as e:
        logger.error(f"Error generating synthetic patients: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=str(e))


@router.post("/{patient_id}/admit")
async def admit_demo_patient_to_hospital(patient_id: str):
    """
    Bridges a synthetic demo patient directly into Metropolitan General's live inpatient/ward repository.
    Enables immediate simulation, triage, and physician review by clinical AI agents.
    """
    try:
        from backend.simulation.orchestrator import orchestrator
        admitted = demo_data_service.admit_to_hospital(patient_id, orchestrator.db)
        return {
            "status": "ADMITTED",
            "message": f"Synthetic patient {admitted.get('name')} successfully admitted into Metropolitan General",
            "patient": admitted,
            "disclaimer": SYNTHETIC_DISCLAIMER,
        }
    except KeyError as ke:
        raise HTTPException(status_code=404, detail=str(ke))
    except Exception as e:
        logger.error(f"Error admitting synthetic patient {patient_id}: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=str(e))
