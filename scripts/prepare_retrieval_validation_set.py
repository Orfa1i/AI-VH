"""
Prepare the approved retrieval validation set (30-50 labelled query->chunk pairs).

System-PROPOSSES, physician-DISPOSES: candidate pairs are produced by the
Phase 1 semantic-hybrid HarrisonAdapter and every label carries
"label_status": "pending physician review". No threshold tuning may use this
set until the owner reviews and approves the labels.

Output: eval/retrieval_validation_v1/labels.jsonl (40 pairs) + README.md.

Owner: Medical Expert (label review) + AI Engineer (generation script).
"""

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from vh.rag.sources.harrison import HarrisonAdapter  # noqa: E402

OUT_DIR = REPO_ROOT / "eval" / "retrieval_validation_v1"

QUERIES = [
    ("RV-CAP-01", "fever productive cough tachypnoea low oxygen consolidation"),
    ("RV-CAP-02", "community-acquired pneumonia CURB-65 severity score"),
    ("RV-CAP-03", "suspected pneumonia chest X-ray diagnostic workup"),
    ("RV-CAP-04", "community-acquired pneumonia empiric antibiotic management"),
    ("RV-ACS-01", "acute substernal chest pressure diaphoresis differential diagnosis"),
    ("RV-ACS-02", "suspected acute coronary syndrome troponin ECG workup"),
    ("RV-ACS-03", "acute coronary syndrome dual antiplatelet management"),
    ("RV-DKA-01", "polyuria polydipsia nausea abdominal pain differential diagnosis"),
    ("RV-DKA-02", "suspected diabetic ketoacidosis anion gap beta-hydroxybutyrate workup"),
    ("RV-DKA-03", "diabetic ketoacidosis fluids insulin management"),
]


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    adapter = HarrisonAdapter()
    pairs = []
    for qid, query in QUERIES:
        hits = adapter.search(query, top_k=4)
        for rank, hit in enumerate(hits, start=1):
            pairs.append(
                {
                    "query_id": qid,
                    "query": query,
                    "rank_proposed": rank,
                    "expected_chunk_id": hit.chunk_id,
                    "expected_chapter": hit.metadata.get("chapter_title"),
                    "expected_page": hit.metadata.get("page"),
                    "proposed_score": round(hit.score, 4),
                    "retrieval_mode": hit.metadata.get("retrieval_mode"),
                    "relevance": "relevant",
                    "label_status": "pending physician review",
                    "is_synthetic": True,
                    "notes": "System-proposed candidate; physician confirms or rejects.",
                }
            )

    labels_path = OUT_DIR / "labels.jsonl"
    with open(labels_path, "w", encoding="utf-8") as f:
        for pair in pairs:
            f.write(json.dumps(pair) + "\n")

    readme = OUT_DIR / "README.md"
    readme.write_text(
        "# Retrieval Validation v1 (PENDING physician review)\n\n"
        f"- **Pairs**: {len(pairs)} (10 queries x top-4 semantic-hybrid candidates)\n"
        "- **Status**: every label is `pending physician review`. DO NOT tune any\n"
        "  threshold on this set until the owner approves the labels.\n"
        "- **Review instructions**: for each pair, mark `relevance` as `relevant`\n"
        "  or `not-relevant`; corrected labels go to `labels.approved.jsonl`.\n"
        "- **Metric plan**: precision@k / recall@k across thresholds\n"
        "  {0.0, 0.01, 0.05, 0.1} on the cosine-similarity scale [0, 1].\n"
        "- **Provenance**: generated by `scripts/prepare_retrieval_validation_set.py`\n"
        "  with Phase 1 `HarrisonAdapter` (semantic-hybrid, all-MiniLM-L6-v2).\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(pairs)} pairs to {labels_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
