"""
Clinical report schema and referential integrity validator for AI Virtual Hospital (AI-VH).
Enforces claim-evidence links, citation traceability, and structured abstention.
Exports JSON Schema for MedGemma constrained decoding.
"""

import json
from pathlib import Path
from typing import Any, Dict, List, Literal, Optional, Set, Union
from pydantic import BaseModel, Field

REPO_ROOT = Path(__file__).resolve().parent.parent.parent.parent


class IntegrityValidationError(ValueError):
    """Base exception for clinical report referential integrity violations."""
    pass


class MissingClaimError(IntegrityValidationError):
    """Raised when differential or recommendation references a non-existent claim_id."""
    pass


class UnresolvedEvidenceError(IntegrityValidationError):
    """Raised when a claim references an evidence_id absent from retrieval context."""
    pass


class EmptyClaimsError(IntegrityValidationError):
    """Raised when a recommendation or differential entry lacks supporting claim_ids."""
    pass


class DifferentialItem(BaseModel):
    """Differential diagnosis entry linked to supporting clinical claims."""
    dx: str = Field(..., description="Diagnosis name")
    likelihood: Literal["high", "moderate", "low"] = Field(..., description="Estimated diagnostic likelihood")
    claim_ids: List[str] = Field(default_factory=list, description="IDs of claims supporting this diagnosis")


class RecommendationItem(BaseModel):
    """Clinical management or diagnostic workup recommendation."""
    text: str = Field(..., description="Actionable clinical recommendation statement")
    claim_ids: List[str] = Field(default_factory=list, description="IDs of claims grounding this recommendation")


class ClaimItem(BaseModel):
    """Verifiable clinical proposition linked to retrieved evidence chunks."""
    claim_id: str = Field(..., description="Unique claim identifier within report")
    text: str = Field(..., description="Verifiable clinical statement")
    type: Literal["diagnostic", "therapeutic", "prognostic", "factual"] = Field(
        ..., description="Clinical classification of claim"
    )
    evidence_ids: List[str] = Field(
        default_factory=list, description="IDs of supporting evidence chunks from retrieval"
    )


class AbstentionItem(BaseModel):
    """Explicit abstention where clinical evidence or patient data is insufficient."""
    question: str = Field(..., description="Clinical question or management issue abstained from")
    reason: str = Field(..., description="Clinical rationale for abstaining from decision")


class ReportProvenance(BaseModel):
    """Provenance tracking execution run, model, prompt template, index, and case."""
    run_id: str = Field(..., description="Generation execution run identifier")
    model_id: str = Field(..., description="Model identifier used for inference")
    prompt_name_version: str = Field(..., description="Prompt template and version in name@version format")
    index_version: str = Field(..., description="Evidence index version utilized")
    case_id: str = Field(..., description="Target patient case identifier")


class ClinicalReport(BaseModel):
    """
    Structured clinical evaluation report generated by MedGemma.
    Every diagnosis and recommendation is grounded in explicit claims,
    and every claim is linked to retrieved evidence chunks.
    """
    patient_summary: str = Field(..., description="Synthesized patient visible presentation summary")
    findings: List[str] = Field(default_factory=list, description="Observed clinical signs, vitals, and findings")
    differential: List[DifferentialItem] = Field(
        default_factory=list, description="Ranked differential diagnoses with likelihood and claim links"
    )
    recommendations: List[RecommendationItem] = Field(
        default_factory=list, description="Diagnostic, therapeutic, or monitoring recommendations"
    )
    claims: List[ClaimItem] = Field(
        default_factory=list, description="Grounded clinical propositions supporting diagnoses and recommendations"
    )
    abstentions: List[AbstentionItem] = Field(
        default_factory=list, description="Explicit abstentions where evidence is insufficient"
    )
    provenance: ReportProvenance = Field(..., description="Execution provenance metadata")


def validate_clinical_report(
    report: ClinicalReport,
    valid_evidence_ids: Optional[Set[str]] = None,
) -> bool:
    """
    Validate schema and enforce strict referential integrity:
    1. Every recommendation must have at least one claim_id.
    2. Every differential entry must have at least one claim_id.
    3. Every claim_id referenced in differential or recommendations must exist in claims.
    4. Every evidence_id referenced in claims must exist in valid_evidence_ids (if provided).
    """
    defined_claims = {c.claim_id for c in report.claims}

    # Check differential entries
    for diff in report.differential:
        if not diff.claim_ids:
            raise EmptyClaimsError(f"Differential diagnosis '{diff.dx}' has empty claim_ids")
        for cid in diff.claim_ids:
            if cid not in defined_claims:
                raise MissingClaimError(
                    f"Differential '{diff.dx}' references non-existent claim_id '{cid}'"
                )

    # Check recommendations
    for rec in report.recommendations:
        if not rec.claim_ids:
            raise EmptyClaimsError(f"Recommendation '{rec.text}' has empty claim_ids")
        for cid in rec.claim_ids:
            if cid not in defined_claims:
                raise MissingClaimError(
                    f"Recommendation '{rec.text}' references non-existent claim_id '{cid}'"
                )

    # Check evidence traceability
    if valid_evidence_ids is not None:
        for claim in report.claims:
            for eid in claim.evidence_ids:
                if eid not in valid_evidence_ids:
                    raise UnresolvedEvidenceError(
                        f"Claim '{claim.claim_id}' references unresolved evidence_id '{eid}' "
                        f"not found in retrieval context"
                    )

    return True


def export_clinical_report_json_schema(
    output_path: Optional[Union[str, Path]] = None,
) -> Dict[str, Any]:
    """
    Export the ClinicalReport Pydantic model JSON Schema to disk.
    Used for MedGemma constrained JSON decoding and external verification.
    """
    target = Path(output_path) if output_path else (REPO_ROOT / "schemas" / "clinical_report.json")
    target.parent.mkdir(parents=True, exist_ok=True)

    schema = ClinicalReport.model_json_schema()
    target.write_text(json.dumps(schema, indent=2), encoding="utf-8")
    return schema
